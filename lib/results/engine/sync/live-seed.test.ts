/**
 * OPERATOR TOOL, not a test in the usual sense. Skipped unless
 * `HYROX_LIVE_SEED=1`.
 *
 * Ingests real HYROX data through the real engine and writes it out as SQL to
 * `RESULTS_SEED_OUT` (default `/tmp/results-seed.sql`), ready for `psql`.
 *
 * Why it exists: the application talks to Supabase over PostgREST with the
 * secret key, but schema work from this machine goes over `psql` with the
 * database password. This bridges the two — it proves the migration, the
 * parser and real ingested data all agree on every column type, constraint and
 * JSONB shape, and it leaves the database populated so the serving API has
 * something real to answer with.
 *
 *   HYROX_LIVE_SEED=1 HYROX_SOURCE_ACCESS=authorised npx vitest run live-seed
 *   psql "$DB" -v ON_ERROR_STOP=1 -f /tmp/results-seed.sql
 *
 * It is idempotent by construction: every insert is `on conflict do update`,
 * keyed the way the engine keys its own upserts.
 */

import { describe, expect, it } from "vitest";
import { writeFileSync } from "node:fs";
import { MemoryResultsRepository } from "../memory-repo";
import { SyncEngine } from "./engine";
import { createHyroxChain } from "../source/hyrox-adapter";
import { SourceFetcher } from "../fetch/fetcher";
import { OutboundBudget } from "../fetch/guard";
import { runSplitsBackfill } from "./splits";
import { recomputeDistributionsForEvent, recomputeGlobalDistributions } from "./distributions";
import { metadataFor } from "./event-metadata";

const suite = process.env.HYROX_LIVE_SEED === "1" ? describe : describe.skip;

/** A real, finished season-8 weekend. */
const SEASON = "season-8";
const DIVISIONS: { code: string; key: string; label: string; sex: "men" | "women" }[] = [
  { code: "H_LR3MS4JI163A", key: "open-men", label: "HYROX Men", sex: "men" },
  { code: "H_LR3MS4JI163A", key: "open-women", label: "HYROX Women", sex: "women" },
  { code: "HD1_LR3MS4JI163B", key: "doubles-men", label: "HYROX Doubles Men", sex: "men" },
];

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};

suite("live seed", () => {
  it("ingests real races and writes loadable SQL", async () => {
    const repo = new MemoryResultsRepository();
    const chain = createHyroxChain(
      new SourceFetcher({
        authorised: true,
        budget: new OutboundBudget({ maxRequests: 90, windowMs: 60_000 }),
        maxAttempts: 3,
      }),
    );
    const engine = new SyncEngine({ repo, adapter: chain });

    // A real weekend. Its city and year come from the HYROX calendar join, so
    // the dates and timezone in the seed are the real ones.
    const city = "London";
    const year = 2026;
    const meta = metadataFor(city, year);

    const event = await repo.upsertEvent({
      slug: `s8-${year}-${city.toLowerCase()}`,
      name: `HYROX ${city} ${year}`,
      city,
      country: meta?.country ?? "United Kingdom",
      countryIso: meta?.countryIso ?? "GB",
      region: meta?.region ?? "UK",
      season: "s8",
      year,
      venue: meta?.venue ?? null,
      status: "final",
      startDatetime: meta?.startDatetime ?? null,
      endDatetime: meta?.endDatetime ?? null,
      tzOffsetMinutes: meta?.tzOffsetMinutes ?? 0,
      startDate: meta?.startDate ?? null,
      endDate: meta?.endDate ?? null,
      athleteCount: 0,
      sourceEventId: "LR3MS4JI163A",
      sourceSeasonPath: SEASON,
      isDemo: false,
      lastSyncedAt: null,
    });

    for (const d of DIVISIONS) {
      const division = await repo.upsertDivision({
        eventId: event.id,
        divisionKey: d.key,
        displayName: d.label,
        entrantCount: 0,
        publishedEntrantCount: null,
        sourceDivisionId: `${d.code}#${d.sex}`,
      });
      const outcome = await engine.syncDivision({
        seasonPath: SEASON,
        event,
        division,
        sourceDivisionId: `${d.code}#${d.sex}`,
      });
      console.log(
        `[seed] ${d.key.padEnd(12)} inserted=${outcome.inserted} quarantined=${outcome.quarantined}`,
      );
    }

    const splits = await runSplitsBackfill(engine, { limit: 25 });
    console.log(`[seed] splits filled=${splits.filled} remaining=${splits.remaining}`);

    await recomputeDistributionsForEvent(repo, event.id);
    await recomputeGlobalDistributions(repo);

    /* ── Emit ─────────────────────────────────────────────────────────── */

    const lines: string[] = [
      "-- Real HYROX results, ingested by the engine and written for psql.",
      "-- Generated by lib/results/engine/sync/live-seed.test.ts",
      "begin;",
    ];

    const ev = [...repo.events.values()][0];
    lines.push(
      `insert into results_events (slug,name,city,country,country_iso,region,season,year,venue,status,start_datetime,end_datetime,tz_offset_minutes,start_date,end_date,athlete_count,source_event_id,source_season_path,is_demo)
values (${[ev.slug, ev.name, ev.city, ev.country, ev.countryIso, ev.region, ev.season].map(q).join(",")},${ev.year},${q(ev.venue)},${q(ev.status)},${q(ev.startDatetime)},${q(ev.endDatetime)},${ev.tzOffsetMinutes},${q(ev.startDate)},${q(ev.endDate)},${ev.athleteCount},${q(ev.sourceEventId)},${q(ev.sourceSeasonPath)},false)
on conflict (slug) do update set name=excluded.name, start_datetime=excluded.start_datetime, end_datetime=excluded.end_datetime, tz_offset_minutes=excluded.tz_offset_minutes, start_date=excluded.start_date, end_date=excluded.end_date, venue=excluded.venue, region=excluded.region, country=excluded.country, country_iso=excluded.country_iso;`,
    );

    for (const d of repo.divisions.values()) {
      lines.push(
        `insert into results_divisions (event_id,division_key,display_name,entrant_count,published_entrant_count,source_division_id,last_seen_hash)
select id,${q(d.divisionKey)},${q(d.displayName)},${d.entrantCount},${q(d.publishedEntrantCount)},${q(d.sourceDivisionId)},${q(d.lastSeenHash)} from results_events where slug=${q(ev.slug)}
on conflict (event_id,division_key) do update set entrant_count=excluded.entrant_count, published_entrant_count=excluded.published_entrant_count, last_seen_hash=excluded.last_seen_hash;`,
      );
    }

    for (const a of repo.athletes.values()) {
      lines.push(
        `insert into results_athletes (slug,name,nationality,gender,source_athlete_id,is_demo,is_anonymised,identity_confidence,needs_identity_review)
values (${q(a.slug)},${q(a.name)},${q(a.nationality)},${q(a.gender)},${q(a.sourceAthleteId)},false,false,${a.identityConfidence},${a.needsIdentityReview})
on conflict (slug) do update set name=excluded.name, nationality=excluded.nationality;`,
      );
    }

    for (const r of repo.results.values()) {
      const athlete = repo.athletes.get(r.athleteId)!;
      const division = repo.divisions.get(r.divisionId)!;
      lines.push(
        `insert into results_results (event_id,division_id,athlete_id,source_result_id,rank_overall,rank_age_group,age_group,sex,finish_time_ms,roxzone_time_ms,status,wave,bib,splits,is_demo)
select e.id, d.id, a.id, ${q(r.sourceResultId)},${q(r.rankOverall)},${q(r.rankAgeGroup)},${q(r.ageGroup)},${q(r.sex)},${q(r.finishTimeMs)},${q(r.roxzoneTimeMs)},${q(r.status)},${q(r.wave)},${q(r.bib)},${q(JSON.stringify(r.splits))}::jsonb,false
from results_events e
join results_divisions d on d.event_id = e.id and d.division_key = ${q(division.divisionKey)}
join results_athletes a on a.slug = ${q(athlete.slug)}
where e.slug = ${q(ev.slug)}
on conflict (source_result_id) do update set rank_overall=excluded.rank_overall, rank_age_group=excluded.rank_age_group, finish_time_ms=excluded.finish_time_ms, roxzone_time_ms=excluded.roxzone_time_ms, status=excluded.status, splits=excluded.splits, bib=excluded.bib;`,
      );
    }

    for (const dist of repo.distributions) {
      lines.push(
        `insert into results_station_distributions (scope,event_id,division_key,station_key,age_group,sex,sample_count,median_ms,mean_ms,percentiles,computed_at)
select ${q(dist.scope)}, ${dist.eventId ? `(select id from results_events where slug=${q(ev.slug)})` : "null"}, ${q(dist.divisionKey)},${q(dist.stationKey)},null,null,${dist.sampleCount},${q(dist.medianMs)},${q(dist.meanMs)},${q(JSON.stringify(dist.percentiles))}::jsonb, now()
on conflict (scope,event_id,division_key,station_key,age_group,sex) do update set sample_count=excluded.sample_count, median_ms=excluded.median_ms, mean_ms=excluded.mean_ms, percentiles=excluded.percentiles, computed_at=now();`,
      );
    }

    lines.push("commit;");

    const out = process.env.RESULTS_SEED_OUT ?? "/tmp/results-seed.sql";
    writeFileSync(out, lines.join("\n\n") + "\n");
    console.log(
      `[seed] wrote ${lines.length} statements to ${out} — ` +
        `${repo.events.size} event, ${repo.divisions.size} divisions, ` +
        `${repo.athletes.size} athletes, ${repo.results.size} results, ` +
        `${repo.distributions.length} distributions`,
    );

    expect(repo.results.size).toBeGreaterThan(100);
    expect(repo.athletes.size).toBeGreaterThan(100);
  }, 300_000);
});
