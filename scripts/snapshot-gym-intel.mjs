/**
 * Redis → data/gym-intel.json.
 *
 * The pages read a file, not Redis: 5,856 pages must not each make a network
 * call, and a build must not fail because a third-party store is having a bad
 * morning. This is the bridge, run on demand before a deploy.
 *
 * Nothing here invents or smooths anything. It copies counters across and
 * stamps the date. A gym nobody has reported on simply is not in the file, and
 * its page says nothing about its equipment — which is the truthful outcome.
 *
 * Run: node scripts/snapshot-gym-intel.mjs [--dry-run]
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

const URL_ = process.env.UPSTASH_REDIS_REST_URL;
const TOKEN = process.env.UPSTASH_REDIS_REST_TOKEN;
const OUT = path.join(process.cwd(), "data", "gym-intel.json");
const dryRun = process.argv.includes("--dry-run");

if (!URL_ || !TOKEN) {
  console.error(
    "UPSTASH_REDIS_REST_URL and UPSTASH_REDIS_REST_TOKEN are not set.\n" +
      "Nothing written — an empty snapshot would silently erase real reports.",
  );
  process.exit(1);
}

async function cmd(...args) {
  const res = await fetch(URL_, {
    method: "POST",
    headers: { authorization: `Bearer ${TOKEN}`, "content-type": "application/json" },
    body: JSON.stringify(args),
  });
  if (!res.ok) throw new Error(`Redis ${res.status}: ${await res.text()}`);
  return (await res.json()).result;
}

const places = (await cmd("SMEMBERS", "gym-intel:places")) ?? [];
console.log(`${places.length} places have reports.`);

const out = {};
let reports = 0;

for (const place of places) {
  const flat = (await cmd("HGETALL", `gym-intel:${place}`)) ?? [];
  const entry = {};
  // Upstash returns a flat [field, value, field, value, …] array.
  for (let i = 0; i < flat.length; i += 2) {
    const [gym, station, answer] = String(flat[i]).split(":");
    const n = Number(flat[i + 1]) || 0;
    if (!gym || !station || (answer !== "yes" && answer !== "no")) continue;
    entry[gym] ??= {};
    entry[gym][station] ??= { yes: 0, no: 0 };
    entry[gym][station][answer] += n;
    reports += n;
  }
  if (Object.keys(entry).length) out[place] = entry;
}

console.log(`${reports} individual reports across ${Object.keys(out).length} places.`);

if (dryRun) {
  console.log("--dry-run: nothing written.");
} else {
  writeFileSync(
    OUT,
    JSON.stringify(
      {
        generatedAt: new Date().toISOString().slice(0, 10),
        note:
          "Athlete-reported gym equipment. Generated by " +
          "scripts/snapshot-gym-intel.mjs from Redis. Do not edit by hand.",
        places: out,
      },
      null,
      2,
    ) + "\n",
  );
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
}
