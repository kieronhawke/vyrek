/**
 * Builds the identity layer for every city that has hosted a HYROX race
 * outside the UK.
 *
 * Kieron's directive of 2 August 2026: wherever there has been a HYROX, there
 * should be a personal trainer page and a HYROX training page.
 *
 * Input:
 *   data/hyrox/races.normalised.json  — 113 races scraped from hyrox.com
 *   data/hyrox/races.geocoded.json    — city and venue coordinates
 *   data/locations/registry.json      — the 1,882 UK towns, for collisions
 *
 * Output:
 *   data/locations/race-cities.json
 *
 * Deliberately a separate file from registry.json rather than more rows in it.
 * The UK registry is generated by scripts/build-uk-locations.mjs from GeoNames
 * and carries region and county, which are the two things the UK page templates
 * and their directory layers are built on. A Tokyo row has neither, and folding
 * it in would mean every UK consumer learning to skip foreign rows. The two
 * catalogues answer different questions, so they stay two files.
 *
 * The five UK host cities are excluded: London, Manchester, Birmingham,
 * Glasgow and Cardiff already have pages built from the UK registry, and their
 * race data reaches those pages through lib/hyrox-races.ts instead.
 *
 * Run: node scripts/build-race-cities.mjs [--dry-run]
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const NORMALISED = path.join(ROOT, "data", "hyrox", "races.normalised.json");
const GEOCODED = path.join(ROOT, "data", "hyrox", "races.geocoded.json");
const UK_REGISTRY = path.join(ROOT, "data", "locations", "registry.json");
const OUT = path.join(ROOT, "data", "locations", "race-cities.json");

const TODAY = new Date().toISOString().slice(0, 10);
const dryRun = process.argv.includes("--dry-run");

function slugify(s) {
  return s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/**
 * Country slugs used to disambiguate a city whose name a UK town already owns.
 * Short forms only where the long one reads badly in a URL.
 */
const COUNTRY_SLUG_ALIAS = {
  "United States": "usa",
  "United Kingdom": "uk",
  "South Korea": "korea",
  "South Africa": "south-africa",
  "New Zealand": "new-zealand",
  "Hong Kong": "hong-kong",
  Türkiye: "turkey",
};

function countrySlug(country) {
  return COUNTRY_SLUG_ALIAS[country] ?? slugify(country);
}

const races = (() => {
  const d = JSON.parse(readFileSync(NORMALISED, "utf8"));
  return Array.isArray(d) ? d : d.races;
})();
const geo = JSON.parse(readFileSync(GEOCODED, "utf8"));
const ukSlugs = new Set(
  JSON.parse(readFileSync(UK_REGISTRY, "utf8")).locations.map((l) => l.slug),
);

// ── Group races by host city ─────────────────────────────────────────
const byCity = new Map();
for (const r of races) {
  if (!r.city) continue;
  const key = slugify(r.city);
  if (!byCity.has(key)) byCity.set(key, []);
  byCity.get(key).push(r);
}

const cities = [];
const collisions = [];
let skippedUk = 0;

for (const [key, cityRaces] of [...byCity].sort((a, b) => a[0].localeCompare(b[0]))) {
  const first = cityRaces[0];

  /* The UK host cities already have pages from the UK registry. Their races
     reach those pages through the shared race layer, not through here. */
  if (first.country === "United Kingdom") {
    skippedUk++;
    continue;
  }

  const cityGeo = geo.cities[key];
  if (!cityGeo || cityGeo.lat == null) {
    console.log(`  ! ${key} has no coordinates — skipped`);
    continue;
  }

  /* A city whose name a UK town already owns takes a country-qualified slug.
     The UK town keeps the bare one: it is already indexed and linked, and
     breaking a live URL to hand it to a bigger market is a trade to make
     deliberately, not as a side effect of adding pages. Four cities hit this:
     Perth, Boston, Houston and Portland. */
  let slug = key;
  if (ukSlugs.has(key)) {
    slug = `${key}-${countrySlug(first.country)}`;
    collisions.push({ city: first.city, country: first.country, slug });
  }

  cities.push({
    slug,
    /** The bare slug, when it differs — used to cross-link the UK namesake. */
    bareSlug: slug === key ? undefined : key,
    name: first.city,
    country: first.country,
    countrySlug: countrySlug(first.country),
    continent: first.continent,
    lat: cityGeo.lat,
    lng: cityGeo.lng,
    source: cityGeo.source,
    verifiedOn: cityGeo.verifiedOn,
    races: cityRaces
      .map((r) => {
        const v = geo.venues[r.slug] ?? {};
        return {
          slug: r.slug,
          name: r.name,
          venue: r.venue,
          venueName: r.venueName,
          /** False when HYROX has not yet published a venue for this race. */
          venueAnnounced: v.announced !== false,
          lat: v.lat ?? null,
          lng: v.lng ?? null,
          startDate: r.startDate,
          endDate: r.endDate,
          isWorldChampionship: r.isWorldChampionship || undefined,
          isYoungstars: r.isYoungstars || undefined,
          sourceUrl: r.sourceUrl,
        };
      })
      .sort((a, b) => String(a.startDate).localeCompare(String(b.startDate))),
  });
}

// ── Report ───────────────────────────────────────────────────────────
const byCountry = {};
for (const c of cities) byCountry[c.country] = (byCountry[c.country] ?? 0) + 1;

console.log(
  `${cities.length} international race cities across ${Object.keys(byCountry).length} countries.`,
);
console.log(`${skippedUk} UK host cities left to the UK registry.`);
console.log(
  `${cities.reduce((n, c) => n + c.races.length, 0)} races attached.`,
);

if (collisions.length) {
  console.log(`\n${collisions.length} name collisions with UK towns, qualified:`);
  for (const c of collisions) {
    console.log(`  ${c.city}, ${c.country} → /${c.slug}`);
  }
}

const noVenue = cities.flatMap((c) =>
  c.races.filter((r) => !r.venueAnnounced).map((r) => r.slug),
);
if (noVenue.length) {
  console.log(`\n${noVenue.length} races have no venue announced yet:`);
  for (const s of noVenue) console.log(`  ${s}`);
}

if (dryRun) {
  console.log("\n--dry-run: nothing written.");
} else {
  writeFileSync(
    OUT,
    JSON.stringify(
      {
        generatedAt: TODAY,
        note:
          "Generated by scripts/build-race-cities.mjs from the HYROX race " +
          "calendar. Do not edit by hand.",
        sources: {
          races: "https://hyrox.com/ (event-sitemap.xml)",
          coordinates: "https://nominatim.openstreetmap.org/",
        },
        cities,
      },
      null,
      2,
    ) + "\n",
  );
  console.log(`\nWrote ${path.relative(ROOT, OUT)}`);
}
